const CYRILLIC = /[А-Яа-яІіЇїЄєҐґ]/;

export function translateRuntimeToEnglish(message: string): string {
  const text = message.trim();
  if (!CYRILLIC.test(text)) return message;
  const hit = exact[text];
  if (hit) return hit;
  for (const [pattern, render] of patterns) {
    const match = text.match(pattern);
    if (match) return render(match, translateRuntimeToEnglish);
  }
  // Fall back to sentence-by-sentence lookup (messages are sometimes concatenated).
  const sentences = text.match(/[^.!?…]+[.!?…]+|[^.!?…]+$/g);
  if (sentences && sentences.length > 1) {
    const parts = sentences.map(sentence => {
      const s = sentence.trim();
      return exact[s] ?? patterns.reduce<string | null>((done, [pattern, render]) => {
        if (done !== null) return done;
        const match = s.match(pattern);
        return match ? render(match, translateRuntimeToEnglish) : null;
      }, null) ?? s;
    });
    return parts.join(" ");
  }
  return message;
}

export function translateRuntime(language: "en" | "uk", message: string): string {
  return language === "en" ? translateRuntimeToEnglish(message) : message;
}

